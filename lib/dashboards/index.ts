import "server-only";

import {
  OpenUIApiError,
  OpenUIClient,
  ToolExecutionError,
  type Dashboard,
  type DashboardOptions,
  type DataTool,
} from "@openuidev/server";
import { parseMessage } from "@openuidev/lang-core";

import { config, secrets } from "@/config";
import { getDb } from "@/lib/db";
import { logError } from "@/lib/log";
import { appFacts } from "@/lib/orgs/access";
import { can } from "@/lib/orgs/policy";
import { ToolError, toolsFor, type Tool, type ToolContext } from "@/lib/tools";

import promptOptions from "./generated/dashboard.prompt.json";
import spec from "./generated/dashboard.spec.json";
import { appGroups } from "./cloud";
import { createDashboardService, type DashboardService } from "./service";


let client: OpenUIClient | undefined;
let dashboards: Dashboard<ToolContext> | undefined;
let service: DashboardService | undefined;

/** OpenUI Cloud, as configured: its API and the THESYS_API_KEY secret. */
export function getOpenUI(): OpenUIClient {
  client ??= new OpenUIClient({ apiKey: secrets.thesysApiKey(), baseUrl: config().openui.apiUrl });
  return client;
}

/**
 * Live dashboards: generated by OpenUI Cloud from @openuidev/dashboard-library, loading
 * their data through every source's dashboard tools. Defined once; who a call
 * is for travels in the context: the user, the app and its org, and the
 * app group their access earns them (lib/dashboards/cloud).
 */
export function getDashboards(): Dashboard<ToolContext> {
  dashboards ??= getOpenUI().defineDashboard<ToolContext>({
    library: spec as unknown as DashboardOptions<ToolContext>["library"],
    model: config().openui.dashboardModel,
    reasoningEffort: config().openui.dashboardReasoningEffort,
    promptOptions,
    tools: dataTools(),
  });
  return dashboards;
}

export function getDashboardService(): DashboardService {
  service ??= createDashboardService({ db: getDb() });
  return service;
}


/** Whether a Cloud failure only means the dashboard isn't there (any more). */
const isGone = (error: unknown) => error instanceof OpenUIApiError && error.status === 404;

/**
 * A dashboard's stored program (OpenUI Lang: its layout, components and the
 * query behind each one), read from OpenUI Cloud with the API key once our
 * own record says the caller can open the app it's in.
 */
export async function readDashboard(
  userId: string,
  appId: string,
  artifactId: string,
): Promise<
  | { ok: true; title: string; description: string | null; program: string }
  | { ok: false; reason: "not_found" | "cloud_failed" }
> {
  const dashboard = (await getDashboardService().list(userId, appId)).find((row) => row.artifactId === artifactId);
  if (!dashboard) return { ok: false, reason: "not_found" };
  try {
    const { content } = await getOpenUI().artifacts.get(artifactId);
    return { ok: true, title: dashboard.title, description: dashboard.description, program: content };
  } catch (error) {
    if (isGone(error)) return { ok: false, reason: "not_found" };
    logError("dashboards.read", error);
    return { ok: false, reason: "cloud_failed" };
  }
}

export type DeleteResult = { ok: true } | { ok: false; reason: "not_found" | "cloud_failed" };

/**
 * Deletes one of an app's dashboards, for anyone who can change the app,
 * whoever created the dashboard: in OpenUI Cloud first (with the API key),
 * then OpenDashboards' record of it. If Cloud fails, the record stays, so the
 * sidebar never hides a dashboard that still exists.
 */
export async function deleteDashboard(userId: string, appId: string, artifactId: string): Promise<DeleteResult> {
  const dashboard = await getDashboardService().findByArtifact(userId, artifactId);
  if (!dashboard || dashboard.appId !== appId || !can("dashboard", "delete", dashboard.grant.facts)) return { ok: false, reason: "not_found" };
  if (!(await deleteDashboardsInCloud([artifactId]))) return { ok: false, reason: "cloud_failed" };
  await getDashboardService().remove(userId, appId, artifactId);
  return { ok: true };
}

/**
 * Deletes every dashboard of an app in OpenUI Cloud, before the app itself
 * goes. For the app's owner, whoever created each dashboard. Returns false if
 * any couldn't be deleted.
 */
export async function deleteAppDashboardsInCloud(userId: string, appId: string): Promise<boolean> {
  // Not theirs to delete: the app's own delete refuses them, so there's nothing to do here.
  if (!can("app", "delete", (await appFacts(getDb(), userId, appId))?.facts ?? null)) return true;
  const all = await getDashboardService().list(userId, appId);
  return deleteDashboardsInCloud(all.map(({ artifactId }) => artifactId));
}

/**
 * Shares dashboards with their app's two groups, so whoever our database lets
 * into the app can open them in OpenUI Cloud: the view group to view, the
 * edit group to edit. With the API key, whoever created each dashboard.
 * Sharing one that's already shared changes nothing. Returns false if any
 * couldn't be shared.
 */
export async function shareDashboardsWithApp(appId: string, artifactIds: string[]): Promise<boolean> {
  const groups = appGroups(appId);
  const results = await Promise.allSettled(
    artifactIds.map(async (artifactId) => {
      await getOpenUI().artifacts.share(artifactId, { type: "group", id: groups.view, access: "view" });
      await getOpenUI().artifacts.share(artifactId, { type: "group", id: groups.edit, access: "edit" });
    }),
  );
  const failed = results.filter((result) => result.status === "rejected");
  for (const failure of failed) logError("dashboards.share", (failure as PromiseRejectedResult).reason);
  return failed.length === 0;
}

/**
 * Deletes dashboards in OpenUI Cloud with the API key, acting as the org:
 * whoever made them. The caller has already checked, in our database, that
 * this user may delete them. One that's already gone counts as deleted.
 * Returns false if any couldn't be deleted.
 */
export async function deleteDashboardsInCloud(artifactIds: string[]): Promise<boolean> {
  const results = await Promise.allSettled(
    artifactIds.map((artifactId) =>
      getOpenUI()
        .artifacts.delete(artifactId)
        .catch((error) => {
          if (isGone(error)) return;
          throw error;
        }),
    ),
  );
  const failed = results.filter((result) => result.status === "rejected");
  for (const failure of failed) logError("dashboards.deleteWorkspace", (failure as PromiseRejectedResult).reason);
  return failed.length === 0;
}

/** Every source's dashboard tools, in the shape the interpreter runs. */
function dataTools(): Record<string, DataTool<ToolContext>> {
  return Object.fromEntries(toolsFor("dashboard").map((tool) => [tool.name, asDataTool(tool)]));
}

/** One tool as the interpreter runs it. Exported for tests. */
export function asDataTool(tool: Tool): DataTool<ToolContext> {
  return {
    description: tool.description,
    parameters: tool.parameters,
    output: tool.output,
    async execute(args, context, { signal }) {
      try {
        return await tool.run(args, context, { signal, caller: "dashboard" });
      } catch (error) {
        if (error instanceof ToolError) {
          // Reported even when the dashboard's own script catches the error and carries on.
          if (error.code === "reauth_required") context.onSignInLost?.();
          throw new ToolExecutionError(error.message, error.code, 400);
        }
        throw error;
      }
    },
  };
}

/**
 * The artifact a create/edit response points at. The response is OpenUI
 * Cloud's: a sentence plus a content line read with react-lang's
 * `parseMessage`, the parser LiveArtifactRenderer reads it with.
 */
export function artifactOf(response: string): { id: string; title?: string } | null {
  const { attributes } = parseMessage(response);
  const id = typeof attributes.artifact_id === "string" ? attributes.artifact_id : null;
  if (!id) return null;
  return { id, title: typeof attributes.name === "string" ? attributes.name : undefined };
}
