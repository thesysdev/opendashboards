import "server-only";

import {
  OpenUIClient,
  ToolExecutionError,
  type Dashboard,
  type DashboardOptions,
  type DataTool,
} from "@openuidev/server";
import { parseMessage } from "@openuidev/lang-core";

import { config, secrets } from "@/config";
import { getDb } from "@/lib/db";
import { logError } from "@/lib/log";
import { ToolError, toolsFor, type ToolContext } from "@/lib/tools";

import promptOptions from "./generated/dashboard.prompt.json";
import spec from "./generated/dashboard.spec.json";
import { createDashboardService, type DashboardService } from "./service";


let client: OpenUIClient | undefined;
let dashboards: Dashboard<ToolContext> | undefined;
let service: DashboardService | undefined;

/** OpenUI Cloud, as configured: its API and the THESYS_API_KEY secret. */
export function getOpenUI(): OpenUIClient {
  client ??= new OpenUIClient({ apiKey: secrets.thesysApiKey(), baseUrl: config().openui.apiUrl });
  return client;
}

/**
 * Live dashboards: generated by OpenUI Cloud from @openuidev/dashboard-library, loading
 * their data through every source's dashboard tools. Defined once; who a call
 * is for travels in the context ({ userId, appId }).
 */
export function getDashboards(): Dashboard<ToolContext> {
  dashboards ??= getOpenUI().defineDashboard<ToolContext>({
    library: spec as unknown as DashboardOptions<ToolContext>["library"],
    model: config().openui.model,
    promptOptions,
    tools: dataTools(),
  });
  return dashboards;
}

export function getDashboardService(): DashboardService {
  service ??= createDashboardService({ db: getDb() });
  return service;
}


/**
 * Deletes a dashboard in OpenUI Cloud, as its owner. The server SDK has no
 * delete, so this calls Cloud's API with the user's own frontend token, the
 * same request react-ui's `useArtifactDelete` makes from the browser.
 * One that's already gone counts as deleted.
 */
async function deleteInCloud(userId: string, artifactId: string): Promise<void> {
  const { token } = await getOpenUI().createFrontendToken({ userId });
  const response = await fetch(`${config().openui.apiUrl}/v1/artifacts/${encodeURIComponent(artifactId)}`, {
    method: "DELETE",
    headers: { "x-thesys-frontend-token": token },
    cache: "no-store",
  });
  if (!response.ok && response.status !== 404) {
    throw new Error(`OpenUI Cloud refused to delete the dashboard (HTTP ${response.status})`);
  }
}

/**
 * A dashboard's stored program (OpenUI Lang: its layout, components and the
 * query behind each one), read from OpenUI Cloud as its owner. As with
 * delete, the server SDK has no read, so this calls Cloud's API with the
 * user's own frontend token.
 */
export async function readDashboard(
  userId: string,
  appId: string,
  artifactId: string,
): Promise<
  | { ok: true; title: string; description: string | null; program: string }
  | { ok: false; reason: "not_found" | "cloud_failed" }
> {
  const dashboard = (await getDashboardService().list(userId, appId)).find((row) => row.artifactId === artifactId);
  if (!dashboard) return { ok: false, reason: "not_found" };
  try {
    const { token } = await getOpenUI().createFrontendToken({ userId });
    const response = await fetch(`${config().openui.apiUrl}/v1/artifacts/${encodeURIComponent(artifactId)}`, {
      headers: { "x-thesys-frontend-token": token },
      cache: "no-store",
    });
    if (response.status === 404) return { ok: false, reason: "not_found" };
    if (!response.ok) throw new Error(`OpenUI Cloud refused to read the dashboard (HTTP ${response.status})`);
    const body = (await response.json()) as { content?: unknown };
    const program = typeof body.content === "string" ? body.content : JSON.stringify(body.content ?? "");
    return { ok: true, title: dashboard.title, description: dashboard.description, program };
  } catch (error) {
    logError("dashboards.read", error);
    return { ok: false, reason: "cloud_failed" };
  }
}

export type DeleteResult = { ok: true } | { ok: false; reason: "not_found" | "cloud_failed" };

/**
 * Deletes one of an app's dashboards: in OpenUI Cloud first, then OpenDashboards'
 * record of it. If Cloud fails, the record stays, so the sidebar never hides
 * a dashboard that still exists.
 */
export async function deleteDashboard(userId: string, appId: string, artifactId: string): Promise<DeleteResult> {
  const dashboard = await getDashboardService().findByArtifact(userId, artifactId);
  if (!dashboard || dashboard.appId !== appId) return { ok: false, reason: "not_found" };
  try {
    await deleteInCloud(userId, artifactId);
  } catch (error) {
    logError("dashboards.delete", error);
    return { ok: false, reason: "cloud_failed" };
  }
  await getDashboardService().remove(userId, appId, artifactId);
  return { ok: true };
}

/**
 * Deletes every dashboard of an app in OpenUI Cloud, before the app itself
 * goes. Returns false if any couldn't be deleted.
 */
export async function deleteAppDashboardsInCloud(userId: string, appId: string): Promise<boolean> {
  const all = await getDashboardService().list(userId, appId);
  const results = await Promise.allSettled(all.map(({ artifactId }) => deleteInCloud(userId, artifactId)));
  const failed = results.filter((result) => result.status === "rejected");
  for (const failure of failed) logError("dashboards.deleteApp", (failure as PromiseRejectedResult).reason);
  return failed.length === 0;
}

/** Every source's dashboard tools, in the shape the interpreter runs. */
function dataTools(): Record<string, DataTool<ToolContext>> {
  return Object.fromEntries(
    toolsFor("dashboard").map((tool) => [
      tool.name,
      {
        description: tool.description,
        parameters: tool.parameters,
        output: tool.output,
        async execute(args, context, { signal }) {
          try {
            return await tool.run(args, context, { signal, caller: "dashboard" });
          } catch (error) {
            if (error instanceof ToolError) throw new ToolExecutionError(error.message, error.code, 400);
            throw error;
          }
        },
      } satisfies DataTool<ToolContext>,
    ]),
  );
}

/**
 * The artifact a create/edit response points at. The response is OpenUI
 * Cloud's: a sentence plus a content line read with react-lang's
 * `parseMessage`, the parser LiveArtifactRenderer reads it with.
 */
export function artifactOf(response: string): { id: string; title?: string } | null {
  const { attributes } = parseMessage(response);
  const id = typeof attributes.artifact_id === "string" ? attributes.artifact_id : null;
  if (!id) return null;
  return { id, title: typeof attributes.name === "string" ? attributes.name : undefined };
}
